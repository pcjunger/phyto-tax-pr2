# Flag phytoplankton taxa using PR2 v4.14 (8 taxonomic ranks).
#
# Requires the output of phyto_tax() from phyto-tax-pr2-v4.1.4.R,
# with columns: Domain, Supergroup, Division, Class, Order, Family,
# Genus, Species, and taxo_phyto.
#
# Unlike the simplified version, this version distinguishes
# Yes / No / Uncertain for Dinophyceae.
# No package dependencies; operates on a data.frame or tibble.

flag_phyto <- function(data) {
  ranks <- c("Domain", "Supergroup", "Division", "Class",
             "Order", "Family", "Genus", "Species")
  required <- c(ranks, "taxo_phyto")
  missing_columns <- setdiff(required, names(data))
  if (length(missing_columns)) {
    stop("Missing required columns: ", paste(missing_columns, collapse = ", "))
  }

  # Phototrophic Dinophyceae genera (ported from the PR2 v5.0.0 script).
  photo_dino <- c(
    "Pileidinium", "Posoniella", "Ceratium", "Neoceratium", "Protoceratium", "Ceratocorys", "Pyrodinium", "Alexandrium", "Amylax",
    "Gonyaulax", "Lingulodinium", "Coolia", "Ostreopsis", "Pyrocystis", "Fragilidium", "Pyrophacus", "Testudodinium", "Brachidinium",
    "Akashiwo", "Amphidinium", "Apicoporus", "Bispinodinium", "Cochlodinium", "Gymnodinium", "Gyrodinium", "Paragymnodinium",
    "Margalefidinium", "Barrufeta", "Moestrupia", "Lepidodinium", "Spiniferodinium", "Togula", "Torodinium", "Hemidinium", "Karenia",
    "Karlodinium", "Takayama", "Polykrikos", "Jadwigia", "Heterodinium", "Woloszynskia", "Blastodinium", "Adenoides", "Peridinium",
    "Scrippsiella", "Peridiniopsis", "Amphidiniella", "Thecadinium", "Ensiculifera", "Azadinium", "Brandtodinium", "Bysmatrum",
    "Glenodiniopsis", "Cachonina", "Heterocapsa", "Durinskia", "Galeidinium", "Kryptoperidinium", "Herdmania", "Calciodinellum",
    "Glenodinium", "Leonella", "Parvodinium", "Pentapharsodinium", "Theleodinium", "Thoracosphaera", "Gloeodinium", "Phytodinium",
    "Prorocentrum", "Biecheleria", "Polarella", "Pelagodinium", "Protodinium", "Borghiella", "Symbiodinium", "Spatulodinium",
    "Cladocopium", "Breviolum", "Durusdinium", "Symbiodiniaceae_X", "Effrenium", "Fugacium", "unclassified_Symbiodiniaceae", "Zooxanthella",
    "Ansanella", "Biecheleriopsis", "Centrodinium", "Fukuyoa", "Gambierdiscus", "Spiniferites", "Tripos"
  )

  non_photo_dino <- c(
    "Chytriodinium", "Crypthecodinium", "Diplopsalopsis", "Impagidinium", "Islandinium",
    "Nusuttodinium", "Oodinium", "Paulsenella", "Protoperidinium", "Sinophysis", "Warnowia"
  )

  # Includes Colpodellaceae, already excluded in the v5 simplified flagger.
  non_photo_groups <- c(
    "MOCH-3", "MOCH-4", "Pteridomonas", "Ciliophrys_infusionum", "Pedospumella",
    "Spumella", "Poteriospumella", "Oikomonas",
    "Chrysophyceae_Clade-F", "Chrysophyceae_Clade-G", "Chrysophyceae_Clade-H",
    "Chrysophyceae_Clade-I", "Chrysophyceae_Clade-EC2H", "Chrysophyceae_Clade-EC2I",
    "Colpodellaceae"
  )

  # In PR2 v4.14, Eustigmatophyceae and Xanthophyceae fall into
  # the broad 'Other Ochrophytes' group generated by phyto_tax().
  # These explicitly phototrophic classes must be rescued first.
  other_photo <- c(
    "Dictyochophyceae", "Eustigmatophyceae", "Xanthophyceae",
    "Chrysoparadoxophyceae", "Olisthodiscophyceae", "Synchromophyceae",
    "Euglenophyceae"
  )

  # Labels taken from phyto-tax-pr2-v4.1.4.R (not the v5 labels).
  non_phyto_labels <- c(
    "Other Ochrophytes", "Other Stramenopiles",
    "Unclassified Archaeplastida", "Unclassified Stramenopiles", "Other"
  )

  # Vectorised membership test; unlike apply(..., 1, ...), it scales to
  # large taxonomy tables without row-wise matrix conversion.
  matches_any_rank <- function(values, columns) {
    hit <- rep(FALSE, nrow(data))
    for (col in columns) hit <- hit | (data[[col]] %in% values)
    hit
  }

  is_dino <- data$Class %in% "Dinophyceae"
  # PR2 v4.14 uses '*' for unresolved taxonomic ranks;
  # PR2 v5 instead often uses 'unclassified_' prefixes.
  unresolved_dino_order <- is_dino &
    (is.na(data$Order) | grepl("*", data$Order, fixed = TRUE))

  flag <- rep("Yes", nrow(data))

  # Apply rules in reverse order of precedence to reproduce the
  # case_when() priorities of flag-phyto-pr2-5.0.0.R.
  flag[matches_any_rank(non_photo_groups, ranks)] <- "No"
  flag[is_dino & !(data$Genus %in% photo_dino)] <- "Uncertain"
  flag[is_dino & (data$Genus %in% non_photo_dino)] <- "No"
  flag[unresolved_dino_order] <- "Uncertain"
  flag[data$taxo_phyto %in% non_phyto_labels] <- "No"
  flag[matches_any_rank(other_photo, c("Class", "Order"))] <- "Yes"

  data$is_phyto <- flag
  data
}
